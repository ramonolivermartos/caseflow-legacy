CREATE TABLE operators (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    title VARCHAR(140) NOT NULL,
    description VARCHAR(4000) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('NEW','IN_PROGRESS','WAITING','RESOLVED','CLOSED')),
    priority VARCHAR(20) NOT NULL CHECK (priority IN ('LOW','NORMAL','HIGH','URGENT')),
    assignee_id BIGINT REFERENCES operators(id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_tickets_status_created ON tickets(status, created_at DESC, id DESC);
CREATE INDEX idx_tickets_assignee ON tickets(assignee_id);
CREATE INDEX idx_tickets_priority ON tickets(priority);
CREATE TABLE ticket_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES tickets(id),
    author_id BIGINT NOT NULL REFERENCES operators(id),
    body VARCHAR(2000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_comments_ticket ON ticket_comments(ticket_id, created_at, id);
CREATE TABLE ticket_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES tickets(id),
    event_type VARCHAR(40) NOT NULL,
    detail VARCHAR(300) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_history_ticket ON ticket_history(ticket_id, created_at, id);
